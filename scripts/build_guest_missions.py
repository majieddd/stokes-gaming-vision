"""Build the GTA guest-series canvas group from the editorial manifest."""
import json
from pathlib import Path


def build(root):
    read = lambda name: json.loads((root / name).read_text())
    plan = read('gta-guest-missions.json')
    cards = []
    for index, entry in enumerate(plan['entries'], 1):
        cards.append(dict(
            id=entry['card'], title=entry['title'], originalTitle=entry['title'],
            channel='Stokes Twins Gaming', formatName=plan['title'],
            preview=entry['preview'], full=entry['asset'], alt='AI concept: ' + entry['scene'],
            variant=f"{index:02} · {entry['guest']}",
            meta=('Recovered thumbnail' if entry.get('recovered') else 'New thumbnail') + ' · Proposed guest',
            summary=entry['goal'] + ' ' + entry['condition'],
            composition=entry['framework'] + ' · ' + entry['composition'],
            comparison=entry['scene'] + ' Expectation match is conditional on recorded gameplay and the guest booking.',
            references=[dict(title='Packaging guidance · October 22, 2026 export',
                channel='Influint Intelligence', url=plan['evidence']['source'],
                standing='Practitioner guidance; no predicted CTR',
                observation='Subject separation and legibility guide the composition. No gaming-channel Studio baseline was supplied.')],
            brief='episode-details.html?variant=' + entry['card'] + '#' + plan['ideaId'],
            briefVariant=entry['card'], retainEpisodeTitle=True, guestMission=True,
            artworkStatus='AI concept · proposed guest · illustrative game world',
            sharedReviewPending=True, shortlisted=False))
    group = dict(id=plan['groupId'], name=plan['title'], short='GTA 6 · Celebrity missions',
        label='8 guest packages', description=plan['summary'], hideTitleOptions=True,
        titleOptions=[plan['title']] + [t for e in plan['entries'] for t in [e['title'], *e['titleOptions']]], cards=cards)
    (root / 'canvas-guest-missions.js').write_text(
        '/* Generated by scripts/build_guest_missions.py. Original guest artwork is retained. */\n'
        'window.STOKES_CANVAS.groups.push(' + json.dumps(group, ensure_ascii=False) + ');\n')
    content = read('video-briefs-content.json')
    content[plan['ideaId']] = dict(
        promise=plan['summary'], channel='Stokes Twins Gaming · guest-mission series',
        how=[
            'A guest enters the GTA room for one clear mission or challenge. Set the goal and rules immediately; the twins and guest take controller turns.',
            'Film a complete story: guest arrival → goal → attempts → complication → final result. Send that finished guest block to a dedicated editor while the room keeps recording.',
            'Publish each guest story as its own video. Save the overall progress, setbacks and final completion for Trapped Until I Beat GTA 6.'],
        intro=[['ALEX', 'We’re trapped until we beat GTA 6—and today, Howie Mandel is joining us.', 'Open on Howie entering the room, then cut to the bank objective.'],
               ['ALAN', 'Before he leaves, we have to finish this heist.', 'Show the mission goal, Howie’s role and the escape target.'],
               ['ALEX', 'Howie, you’re on the controller.', 'Start the first attempt. Each future episode gets its own guest, goal and opening.']],
        turn=['ALAN', 'That changes the plan.', 'Stay with a real mistake or unexpected choice that makes this guest’s attempt its own story.'],
        payoff=['ALEX', 'Let’s see if we did it.', 'Resolve the guest’s mission and final reaction before returning to the main room story.'],
        packaging=['A recognizable guest + one GTA activity + a concrete challenge or stake. Eight episode packages, each with a different guest.',
                   'Seven new images use one twin + the guest + a clear mission centerpiece. The recovered Howie vault image keeps both twins. Each package has a different composition and exact episode title.',
                   'The guest brings a distinct character to a self-contained mission. The series can produce separate uploads while the overall completion challenge develops.'],
        support='Proposed guests and scenarios; bookings, playable objectives and prize terms remain unconfirmed. Kai’s $100,000 race uses sequential timed runs unless supported multiplayer is verified. Influint’s October 22, 2026 public export supplies practitioner packaging guidance, not measured guest results or a forecast. The two other recovered Kai concepts remain in the original guest briefs and production timeline.',
        relatedLinks=[dict(title='Recovered Howie bank-heist concept', url='episode-details.html#guest-howie'),
                      dict(title='Recovered Kai getaway concept', url='episode-details.html#guest-kai'),
                      dict(title='Recovered guest-room concept', url='episode-details.html#guest-room'),
                      dict(title='Rolling guest-episode production plan', url='production-timeline.html#guests'),
                      dict(title='Download all 8 packages and prompts', url='guest-mission-thumbnails/eight-guest-packages.zip'),
                      dict(title='Influint evidence notes and exact prompts', url='gta-guest-missions.json')],
        refs=[['jk6thMe6Vq8', 'The sustained completion challenge supplies the larger story around the standalone guest attempts.'],
              ['xwdhHTtc-3w', 'A specific GTA pursuit is a reference for a clear, self-contained mission objective.']])
    (root / 'video-briefs-content.json').write_text(json.dumps(content, ensure_ascii=False, indent=2) + '\n')
    return plan


if __name__ == '__main__':
    build(Path(__file__).resolve().parents[1])
